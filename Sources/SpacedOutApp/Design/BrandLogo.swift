struct BrandLogoMark: View {
    var size: CGFloat = 18
    var color: Color = .primary

    var body: some View {
        if let image = BrandLogo.swiftUIImage() {
            image
                .resizable()
                .interpolation(.high)
                .scaledToFit()
                .frame(width: size, height: size)
                .foregroundStyle(color)
        } else {
            Image(systemName: "sparkles")
                .font(.system(size: size * 0.8))
                .foregroundStyle(color)
        }
    }
}
